import { readFile, writeFile } from 'node:fs/promises';

// Build a browser module from reviewed data, never from the HTML's scripts.
const catalog = JSON.parse(await readFile(new URL('../data/parts-catalog.json', import.meta.url), 'utf8'));
const entries = [...catalog.items, ...catalog.packages.filter(item => item.kind === 'package')];
const prices = entries.map(item => ({
  id: item.id,
  names: item.aliases || [],
  standard: item.prices.standard.garage ?? item.prices.standard.price,
  supercar: item.prices.supercar.garage ?? item.prices.supercar.price,
  status: item.prices.standard.status,
}));
await writeFile(new URL('../recovered-production/assets/catalog-prices.js', import.meta.url),
  `// Generated by scripts/generate-catalog-prices.mjs. Do not edit.\nexport const catalogVersion = ${JSON.stringify(catalog.source.sha256)};\nexport const catalogPrices = ${JSON.stringify(prices, null, 2)};\n`);
